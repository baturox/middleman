/// A TOML basic string (quoted and escaped).
fn toml_str(s: &str) -> String {
    toml_edit::Value::from(s).to_string().trim().to_string()
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub enum Scope {
    User,
    Project,
}

impl Scope {
    pub fn parse(s: &str) -> Option<Scope> {
        match s {
            "user" => Some(Scope::User),
            "project" => Some(Scope::Project),
            _ => None,
        }
    }
    pub fn as_str(&self) -> &'static str {
        match self {
            Scope::User => "user",
            Scope::Project => "project",
        }
    }
}

pub struct InitOptions {
    pub scope: Scope,
    /// Providers to write; `key_source` is set for keys `init` stored.
    pub providers: Vec<ProviderEntry>,
    pub mode: RoutingMode,
    pub roots: Vec<PathBuf>,
    pub config_path: PathBuf,
    pub project_dir: PathBuf,
    /// Replace existing files (each is backed up first).
    pub force: bool,
}

impl InitOptions {
    /// Preset providers by name, no stored keys (tests and simple callers).
    pub fn preset_entries(names: &[&str]) -> Vec<ProviderEntry> {
        names.iter().map(|n| ProviderEntry::preset(n)).collect()
    }
}

/// Which preset key env vars exist (never their values).
pub fn detect_keys() -> Vec<(&'static str, &'static str, bool)> {
    PRESETS
        .iter()
        .filter_map(|p| {
            p.key_env.map(|k| {
                (
                    p.name,
                    k,
                    std::env::var_os(k).is_some_and(|v| !v.is_empty()),
                )
            })
        })
        .collect()
}

pub fn render_user_config(o: &InitOptions) -> Result<String> {
    let mut s = String::new();
    s.push_str(
        "# middleman user config (generated by `middleman init`). Keys are never inline.\n\n",
    );
    s.push_str("[limits]\nmax_input_chars = 24000\nmax_files = 6\nmax_output_tokens = 2000\nrequest_timeout_s = 120\n\n");
    s.push_str(
        "[budget]\nper_call_usd = 0.05\ndaily_usd = 1.0\nweekly_usd = 4.0\nreserve_usd = 1.0\n\n",
    );
    let roots: Vec<String> = o
        .roots
        .iter()
        .map(|r| format!("{:?}", r.display().to_string()))
        .collect();
    s.push_str(&format!(
        "[paths]\nroots = [{}]\ndeny = []\n\n",
        roots.join(", ")
    ));
    s.push_str("[redact]\nsecrets = \"block\"\npii = \"block\"\n# dictionary_file = \"~/.config/middleman/dictionary.txt\"\n\n");
    s.push_str(&format!(
        "[routing]\nmode = \"{}\"\ndefault_quality = \"cheapest\"\n\n",
        crate::wizard::mode_str(o.mode)
    ));
    for e in &o.providers {
        let name = &e.name;
        s.push_str(&format!("[providers.{name}]\n"));
        let preset = match &e.preset {
            Some(pn) => {
                let Some(p) = presets::find(pn) else {
                    bail!("unknown provider {pn} (see `middleman init --list`)");
                };
                s.push_str(&format!("preset = \"{pn}\"\n"));
                Some(p)
            }
            None => {
                s.push_str("api = \"openai\"\n");
                None
            }
        };
        if let Some(u) = &e.base_url {
            s.push_str(&format!("base_url = {}\n", toml_str(u)));
        }
        if e.local && preset.is_none() {
            s.push_str("trust = \"local\"\n");
        }
        let key_env = preset.and_then(|p| p.key_env);
        if let Some(src) = e.key_source {
            s.push_str(&format!(
                "key_source = \"{}\"   # stored by middleman{}\n",
                src.as_str(),
                key_env
                    .map(|k| format!("; {k} still wins when set"))
                    .unwrap_or_default()
            ));
        } else if let Some(k) = key_env {
            if std::env::var_os(k).is_none() {
                s.push_str(&format!(
                    "# no key yet: run `middleman provider add {name}` (stores it in the OS keychain) or export {k}\n"
                ));
            }
        }
        if let Some(m) = &e.model {
            s.push_str(&format!("model = {}\n", toml_str(m)));
        }
        if preset.is_some_and(|p| !p.verified && e.base_url.is_none()) {
            s.push_str("# base_url from preset (not live-verified); run `middleman doctor`\n");
        }
        s.push('\n');
    }
    if let Some(e) = o.providers.iter().find(|e| e.model.is_some()) {
        s = crate::wizard::pin_model_routes(&s, &e.name)?;
    }
    Ok(s)
}

pub fn render_project_overlay(mode: RoutingMode) -> String {
    format!(
        "# {PROJECT_FILE}: per-repo overlay. It may only TIGHTEN the user config\n\
# (lower budgets/limits/max_sensitivity, add deny globs, disable providers, stricter routing mode).\n\n\
[routing]\nmode = \"{}\"\n\n[paths]\ndeny = []\n",
        crate::wizard::mode_str(mode)
    )
}

fn write_new(path: &Path, text: &str, force: bool, mode: u32, log: &mut Vec<String>) -> Result<()> {
    if path.exists() && !force {
        log.push(format!(
            "exists, kept: {} (`middleman init` can update it)",
            pretty(path)
        ));
        return Ok(());
    }
    if path.exists() {
        let b = crate::wizard::backup_file(path)?;
        log.push(format!("backed up {} to {}", pretty(path), pretty(&b)));
    }
    if let Some(d) = path.parent() {
        std::fs::create_dir_all(d)?;
    }
    crate::fsutil::write_atomic(path, text.as_bytes(), Some(mode))
        .with_context(|| format!("cannot write {}", path.display()))?;
    log.push(format!("wrote {}", pretty(path)));
    Ok(())
}

/// Write middleman's config files. Returns log lines; never touches Claude Code settings.
pub fn init_write(o: &InitOptions) -> Result<Vec<String>> {
    let mut log = Vec::new();
    let text = render_user_config(o)?;
    Config::from_toml(&text).context("the generated config is invalid; nothing was written")?;
    write_new(&o.config_path, &text, o.force, 0o600, &mut log)?;
    if o.scope == Scope::Project {
        write_overlay(o, &mut log)?;
    }
    Ok(log)
}

/// Write `<project>/.middleman.toml` (0644: it is meant to be committed).
pub fn write_overlay(o: &InitOptions, log: &mut Vec<String>) -> Result<()> {
    write_new(
        &o.project_dir.join(PROJECT_FILE),
        &render_project_overlay(o.mode),
        o.force,
        0o644,
        log,
    )
}

#[derive(Debug, Clone, Serialize)]
pub struct Check {
    pub name: String,
    pub ok: bool,
    pub detail: String,
    /// A failed optional check is a warning (exit code stays 0).
    pub optional: bool,
}

impl Check {
    pub fn optional(name: impl Into<String>, ok: bool, detail: impl Into<String>) -> Check {
        Check {
            optional: true,
            ..check(name, ok, detail)
        }
    }

    pub fn label(&self) -> &'static str {
        match (self.ok, self.optional) {
            (true, _) => "[ok]  ",
            (false, true) => "[warn]",
            (false, false) => "[FAIL]",
        }
    }
}

fn check(name: impl Into<String>, ok: bool, detail: impl Into<String>) -> Check {
    Check {
        name: name.into(),
        ok,
        detail: detail.into(),
        optional: false,
    }
}

/// Green/red checklist. Network: `GET /models` and balance per enabled provider (free).
pub async fn doctor(config_path: &Path, cwd: &Path, home: &Path) -> Vec<Check> {
    let mut out = Vec::new();
    let (cfg, overlay) = match Config::load_with_project(config_path, cwd) {
        Ok(c) => c,
        Err(e) => {
            out.push(check(
                "config",
                false,
                format!("{e:#} (run `middleman init` to create one)"),
            ));
            out.extend(crate::claude_setup::wiring_checks(home, cwd));
            return out;
        }
    };
    out.push(check(
        "config",
        true,
        format!("{} valid", config_path.display()),
    ));
    out.push(check(
        "project overlay",
        true,
        overlay
            .map(|p| format!("applied {}", p.display()))
            .unwrap_or_else(|| "none".into()),
    ));
    const EMPTY_DICT: &str =
        "company and product names are not hidden; run `middleman dict suggest`";
    match &cfg.redact.dictionary_file {
        Some(p) if !crate::config::expand_tilde(p).exists() => out.push(Check::optional(
            "dictionary",
            false,
            format!("{} does not exist yet: {EMPTY_DICT}", p.display()),
        )),
        Some(p) => match crate::detect::Dictionary::load(&crate::config::expand_tilde(p)) {
            Ok(d) if d.is_empty() => out.push(Check::optional(
                "dictionary",
                false,
                format!("empty: {EMPTY_DICT}"),
            )),
            Ok(d) => out.push(check("dictionary", true, format!("{} terms", d.len()))),
            Err(e) => out.push(check("dictionary", false, format!("{e:#}"))),
        },
        None => out.push(Check::optional(
            "dictionary",
            false,
            format!("none configured: {EMPTY_DICT}"),
        )),
    }
    match crate::ledger::ensure_private_dir(&cfg.state_dir()) {
        Ok(()) => out.push(check(
            "state dir",
            true,
            cfg.state_dir().display().to_string(),
        )),
        Err(e) => out.push(check("state dir", false, format!("{e:#}"))),
    }
    for (name, p) in &cfg.providers {
        if !p.enabled {
            out.push(check(format!("provider {name}"), true, "disabled"));
            continue;
        }
        let status = p.key_status();
        let key_ok = status.ok();
        out.push(check(
            format!("provider {name}: key"),
            key_ok,
            if key_ok {
                format!("{} (value not shown)", status.describe())
            } else {
                format!("{}; run `middleman provider add {name}`", status.describe())
            },
        ));
        if !key_ok {
            continue;
        }
        let prov = match crate::providers::Provider::from_cfg(name, p, 20) {
            Ok(x) => x,
            Err(e) => {
                out.push(check(
                    format!("provider {name}: client"),
                    false,
                    format!("{e:#}"),
                ));
                continue;
            }
        };
        match prov.models().await {
            Ok(m) => out.push(check(
                format!("provider {name}: reachable"),
                true,
                format!("{} models at {}", m.len(), p.base_url),
            )),
            Err(e) => out.push(check(
                format!("provider {name}: reachable"),
                false,
                e.to_string(),
            )),
        }
        if p.balance != BalanceKind::None {
            match prov.balance().await {
                Ok(b) => out.push(check(
                    format!("provider {name}: balance"),
                    true,
                    format!("${:.4}", b.usd),
                )),
                Err(e) => out.push(check(
                    format!("provider {name}: balance"),
                    false,
                    e.to_string(),
                )),
            }
        }
    }
    let uses_keychain = cfg
        .providers
        .values()
        .any(|p| p.enabled && p.key_source == Some(KeySource::Keychain));
    match crate::keystore::keychain_status() {
        Ok(()) => out.push(check(
            "keychain",
            true,
            format!("{} available", crate::keystore::keychain_name()),
        )),
        Err(e) => out.push(Check {
            optional: !uses_keychain,
            ..check(
                "keychain",
                false,
                format!(
                    "{}: {e}{}",
                    crate::keystore::keychain_name(),
                    if uses_keychain {
                        ""
                    } else {
                        " (keys will be stored in 0600 files instead)"
                    }
                ),
            )
        }),
    }
    match crate::catalog::Catalog::load(&cfg) {
        Some(c) => out.push(check(
            "model catalog",
            c.is_fresh(&cfg),
            format!(
                "{} models, age {}s (run `middleman models refresh` if stale)",
                c.models.len(),
                c.age_secs()
            ),
        )),
        None => out.push(check(
            "model catalog",
            false,
            "not cached; run `middleman models refresh`",
        )),
    }
    match std::env::current_exe() {
        Ok(exe) => out.push(check(
            "binary",
            exe.exists(),
            format!(
                "{}{}",
                exe.display(),
                if exe.to_string_lossy().contains("/release/") {
                    ""
                } else {
                    " (not a release build)"
                }
            ),
        )),
        Err(e) => out.push(check("binary", false, e.to_string())),
    }
    out.extend(crate::claude_setup::wiring_checks(home, cwd));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn init_writes_parseable_config() {
        let d = tempfile::tempdir().unwrap();
        let o = InitOptions {
            scope: Scope::Project,
            providers: vec![
                ProviderEntry {
                    key_source: Some(KeySource::Keychain),
                    model: Some("qwen/qwen3-coder".into()),
                    ..ProviderEntry::preset("openrouter")
                },
                ProviderEntry {
                    base_url: Some("http://localhost:11500/v1".into()),
                    ..ProviderEntry::preset("ollama")
                },
                ProviderEntry {
                    name: "work".into(),
                    base_url: Some("https://llm.example.com/v1".into()),
                    key_source: Some(KeySource::File),
                    ..Default::default()
                },
            ],
            mode: RoutingMode::Confirm,
            roots: vec![d.path().to_path_buf()],
            config_path: d.path().join("cfg/config.toml"),
            project_dir: d.path().to_path_buf(),
            force: false,
        };
        let log = init_write(&o).unwrap();
        assert_eq!(log.len(), 2);
        let c = Config::load(&o.config_path).unwrap();
        assert_eq!(c.routing.mode, RoutingMode::Confirm);
        assert_eq!(
            c.providers["openrouter"].key_source,
            Some(KeySource::Keychain)
        );
        let (c2, f) = Config::load_with_project(&o.config_path, d.path()).unwrap();
        assert!(f.is_some());
        assert_eq!(c2.routing.mode, RoutingMode::Confirm);
        assert_eq!(c.providers["ollama"].base_url, "http://localhost:11500/v1");
        assert_eq!(c.providers["work"].key_source, Some(KeySource::File));
        assert_eq!(c.routes["write_tests"].chain[0], "openrouter");
        // second run does not overwrite
        let log = init_write(&o).unwrap();
        assert!(log[0].starts_with("exists, kept"), "{log:?}");
        // --force backs up first
        let o = InitOptions { force: true, ..o };
        let log = init_write(&o).unwrap();
        assert!(log[0].starts_with("backed up"), "{log:?}");
        assert!(std::fs::read_dir(d.path().join("cfg")).unwrap().any(|e| e
            .unwrap()
            .file_name()
            .to_string_lossy()
            .contains(".bak-")));
    }
}
